/**
 * Solves the minimum-energy path across the Continuity surface and writes it to
 * `src/lib/home/art/landscapePath.ts`.
 *
 * Run after changing the surface in `src/lib/home/art/landscape.ts`:
 *
 *   npx tsx scripts/generate-continuity-path.ts
 *
 * The solve takes several seconds, which is why the result is committed instead
 * of computed in the browser. `tests/test_lib/landscape.test.ts` checks the
 * committed path against the surface, so a stale file fails the suite.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  energy,
  gradient,
  LANDSCAPE_FRAME,
  OFFSCREEN_SEEDS,
  STATION_SEEDS,
} from "../src/lib/home/art/landscape.ts";

interface Point {
  readonly x: number;
  readonly y: number;
}

const OUT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../src/lib/home/art/landscapePath.ts",
);

/** Points per leg while solving, and how many of them are kept in the file. */
const STRING_POINTS = 80;
const KEEP_EVERY = 2;

/** Steepest descent to the bottom of the basin a seed sits in. */
function settle(seed: Point): Point {
  let point = seed;
  for (let step = 0; step < 6000; step++) {
    const slope = gradient(point.x, point.y);
    point = { x: point.x - 6000 * slope.x, y: point.y - 6000 * slope.y };
  }
  return point;
}

function resample(points: readonly Point[], count: number): Point[] {
  const lengths = [0];
  for (let index = 1; index < points.length; index++) {
    lengths.push(
      lengths[index - 1] +
        Math.hypot(points[index].x - points[index - 1].x, points[index].y - points[index - 1].y),
    );
  }
  const total = lengths[lengths.length - 1];
  const out: Point[] = [];
  let cursor = 0;
  for (let index = 0; index <= count; index++) {
    const distance = (total * index) / count;
    while (cursor < lengths.length - 2 && lengths[cursor + 1] < distance) cursor++;
    const span = lengths[cursor + 1] - lengths[cursor] || 1;
    const t = (distance - lengths[cursor]) / span;
    out.push({
      x: points[cursor].x + (points[cursor + 1].x - points[cursor].x) * t,
      y: points[cursor].y + (points[cursor + 1].y - points[cursor].y) * t,
    });
  }
  return out;
}

/**
 * Simplified string method (E, Ren and Vanden-Eijnden, 2007): every interior
 * point takes a step of steepest descent, then the string is respaced to equal
 * arc length. Respacing undoes the slide along the path and leaves the slide
 * across it, so the string comes to rest where there is no slope across it
 * anywhere — the minimum-energy path between the two ends. It needs no tangent
 * estimate, which is what makes a projected string kink on steep ground.
 */
function minimumEnergyPath(from: Point, to: Point): Point[] {
  const rate = 1200;
  let points = resample([from, to], STRING_POINTS);
  for (let iteration = 0; iteration < 6000; iteration++) {
    const moved = points.map((point, index) => {
      if (index === 0 || index === STRING_POINTS) return point;
      const slope = gradient(point.x, point.y);
      return { x: point.x - rate * slope.x, y: point.y - rate * slope.y };
    });
    points = resample(moved, STRING_POINTS);
  }
  return points;
}

/** Two decimals, written the way the formatter keeps them: no trailing zeros. */
const round2 = (value: number) => Math.round(value * 100) / 100;
const tuple = (point: Point) => `[${round2(point.x)}, ${round2(point.y)}]`;
const percent = (value: number) => `${round2(value)}%`;

const minima = STATION_SEEDS.map(settle);
const offscreen = OFFSCREEN_SEEDS.map(settle);
const ends = [offscreen[0], ...minima, offscreen[1]];
const legs = ends.slice(1).map((end, index) => {
  const solved = minimumEnergyPath(ends[index], end);
  const kept = solved.filter((_, k) => k % KEEP_EVERY === 0);
  /* Pin the ends to the settled minima, so neighbouring legs share a point exactly. */
  return [ends[index], ...kept.slice(1, -1), end];
});
const saddles = legs.map((leg) =>
  leg.reduce((best, point) => (energy(point.x, point.y) > energy(best.x, best.y) ? point : best)),
);

const file = `/**
 * Generated by \`scripts/generate-continuity-path.ts\` — do not edit by hand.
 *
 * The minimum-energy path across the surface in \`./landscape.ts\`, as points of
 * its 1440 × 900 frame. Four legs: in from an off-screen basin, through the
 * three stations, and out to the next basin.
 */

type Pair = readonly [number, number];

/** The three stations: true minima of the surface. */
export const CONTINUITY_MINIMA: readonly Pair[] = [
${minima.map((point) => `  ${tuple(point)},`).join("\n")}
];

/** The highest point of each leg: the pass it crosses the ridge at. */
export const CONTINUITY_SADDLES: readonly Pair[] = [
${saddles.map((point) => `  ${tuple(point)},`).join("\n")}
];

export const CONTINUITY_LEGS: readonly (readonly Pair[])[] = [
${legs.map((leg) => `  [\n${leg.map((point) => `    ${tuple(point)},`).join("\n")}\n  ],`).join("\n")}
];

/**
 * Where each station's label is anchored, as a share of the frame. Literal
 * classes so Tailwind's scanner sees them; the test keeps them on the minima.
 */
export const CONTINUITY_STATION_CLASSES: readonly string[] = [
${minima
  .map(
    (point) =>
      `  "left-[${percent((point.x / LANDSCAPE_FRAME.width) * 100)}] top-[${percent((point.y / LANDSCAPE_FRAME.height) * 100)}]",`,
  )
  .join("\n")}
];
`;

fs.writeFileSync(OUT, file);
process.stdout.write(
  `wrote ${path.relative(process.cwd(), OUT)}\nminima ${minima.map(tuple).join(" ")}\nsaddles ${saddles.map(tuple).join(" ")}\n`,
);
